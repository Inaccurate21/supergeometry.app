/** What the button does, in a line ("" when there is nothing to add to its name). */
export function toolInfo(layout: string | null, id: string): string {
  if (layout === "sketch") return SKETCH[id] ?? "";
  if (layout === "settings") return SETTINGS[id] ?? "";
  if (layout === "options") return "";
  return MODEL[id] ?? "";
}
